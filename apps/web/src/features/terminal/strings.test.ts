import { describe, expect, it } from 'vitest';
import { cx } from './strings';

describe('cx.confirmed', () => {
  it('убирает знаменатель эталона «из M»', () => {
    expect(cx.confirmed('BOS определён верно по закрытию тела: 1 из 4.')).toBe('BOS определён верно по закрытию тела — ваших меток: 1.');
  });
  it('текст без счётчика не меняется', () => {
    expect(cx.confirmed('Внешняя и внутренняя структура разделены верно.')).toBe('Внешняя и внутренняя структура разделены верно.');
  });
});
